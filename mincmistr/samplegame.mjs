// Annotated sample game: every Mincmistr card play with the rule that fired. node samplegame.mjs <seed> <rounds> > sample.md
import {createGame,transition} from '../src/engine.mjs';
import {botAction} from '../src/bot.mjs';
import {CARDS,LABEL} from '../src/data.mjs';
import {createMincmistr,mincmistrAction} from './mincmistr.mjs';
const seed=process.argv[2]??'sample-1', upto=Number(process.argv[3]??2);
const seat=1;
let s=createGame({seed,setup:3,side:0,starter:0});
const m=createMincmistr(s,seat,'journeyman');
const G={C:'Construct',M:'Mine',S:'St. Barbara'};
const RULE={cash:'4.1 short of cash → Income','pelicans':'4.2 pelicans → St. Barbara','goal:C':'4.3 plan goal Construct','goal:M':'4.3 plan goal Mine','goal:S':'4.3 plan goal St. Barbara','fallback:I':'4.4 nothing worked → Income','fallback:M':'4.4 nothing worked → Mine','discard':'4.4 discard'};
const out=[`# Sample game, annotated`,``,`Seed \`${seed}\`, setup card 3, Journeyman, generated by \`samplegame.mjs\` from the rules module. The app's Standard rival plays seat 1, standing in for you; the Mincmistr is seat 2. Rounds 1–${upto} are shown in full, then the final score. Town and mine coordinates are the app's labels.`,``];
let lastRound=0, plays=0;
while (s.phase!=='end') {
  if (s.actor!==seat) { s=transition(s,botAction(s,'standard')); continue; }
  const before=s, p=before.players[seat], logLen=before.log.length;
  const rulesBefore={...m.stats.rules};
  const a=mincmistrAction(before,m);
  s=transition(before,a);
  if (before.round>upto) continue;
  if (before.round!==lastRound) { out.push(`## Round ${before.round}`,``); lastRound=before.round; }
  const lines=s.log.slice(logLen).filter(l=>l.actor===seat).map(l=>l.text);
  if (before.phase==='tax') { out.push(`- **Tax**: ${lines.join(' ')}`); continue; }
  if (before.pending.length) { out.push(`  - *Bonus step (${before.pending[0].kind})*: ${lines.join(' ')||'—'}`); continue; }
  plays++;
  const fired=Object.keys(m.stats.rules).find(k=>m.stats.rules[k]!==(rulesBefore[k]??0));
  const card=['Mine / Joker','Mine / Plot','Build / Income','Build / Plot','Rights / Income','Rights / St. Barbara'][a.card];
  out.push(`- **Card play ${plays}.** ${p.coins} g, ${p.pelicans} pelican${p.pelicans===1?'':'s'}, ${p.held.length} right${p.held.length===1?'':'s'} held. Plan card ${m.card.number}: ${m.card.goals.map(g=>G[g]).join(', then ')}, arrow ${m.card.arrow==='low'?'◀':'▶'}.`);
  out.push(`  Rule **${RULE[fired]??fired}**. Plays *${card}*. ${lines.join(' ')}`);
}
const sc=s.result.scores;
out.push(``,`## Result`,``,`| | You (Standard rival) | Mincmistr |`,`|---|---|---|`);
for (const k of ['earned','town','mines','income','reputation','extras','total']) out.push(`| ${k} | ${sc[0][k]} | ${sc[1][k]} |`);
out.push(``,`Rules used over the whole game: ${Object.entries(m.stats.rules).map(([k,v])=>`${RULE[k]??k} ×${v}`).join('; ')}.`);
console.log(out.join('\n'));
